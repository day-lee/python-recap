def quiz_1_to_4():
    """
    [1단계: 문자열 슬라이싱([:]) 훈련]
    기준 문자열: word = "DEVELOPER" (길이: 9)
    """
    word = "DEVELOPER"
    print("=== 1단계: 문자열 슬라이싱 훈련 ===")

    # Q1. 앞의 3글자 "DEV"만 잘라내기
    # 아래 빈칸("")에 들어갈 슬라이싱 코드를 완성하세요.
    ans_1 = word[:3]  
    if ans_1 == "DEV":
        print("Q1: 정답입니다! 🎉")
    else:
        print(f"Q1: 오답입니다. (출력된 값: {ans_1})")

    # Q2. 3번째 인덱스부터 끝까지인 "ELOPER" 잘라내기
    ans_2 = word[3:]  
    if ans_2 == "ELOPER":
        print("Q2: 정답입니다! 🎉")
    else:
        print(f"Q2: 오답입니다. (출력된 값: {ans_2})")

    # Q3. 뒤에서 3글자인 "PER"만 깔끔하게 잘라내기
    ans_3 = word[-3:]  
    if ans_3 == "PER":
        print("Q3: 정답입니다! 🎉")
    else:
        print(f"Q3: 오답입니다. (출력된 값: {ans_3})")

    # Q4. 맨 첫 글자와 맨 마지막 글자를 떼어낸 "EVELOPE" 만들기
    ans_4 = word[1:-1]  
    if ans_4 == "EVELOPE":
        print("Q4: 정답입니다! 🎉")
    else:
        print(f"Q4: 오답입니다. (출력된 값: {ans_4})")
    print()


